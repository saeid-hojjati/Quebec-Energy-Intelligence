import requests
import pandas as pd
from pathlib import Path

url = "https://archive-api.open-meteo.com/v1/archive"

params = {
    "latitude": 45.5019,
    "longitude": -73.5674,
    "start_date": "2019-01-01",
    "end_date": "2026-01-01",
    "hourly": (
        "temperature_2m,"
        "relative_humidity_2m,"
        "precipitation"
    ),
    "timezone": "UTC",
    "models": "era5"
}

response = requests.get(
    url,
    params=params,
    timeout=180
)
response.raise_for_status()

data = response.json()["hourly"]

df = pd.DataFrame({
    "HourUTC": data["time"],
    "TemperatureC": data["temperature_2m"],
    "HumidityPercent": data["relative_humidity_2m"],
    "PrecipitationMM": data["precipitation"]
})

output = Path("Weather_Historical_Montreal.csv")
df.to_csv(output, index=False)

print("Total rows:", len(df))
print("Missing values:")
print(df.isnull().sum())
print("First rows:")
print(df.head())
print("Saved to:", output.resolve())